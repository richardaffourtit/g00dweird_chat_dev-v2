function hash(str) {
    let h = 2166136261;
    for (let i = 0; i < str.length; i += 1) h = Math.imul(h ^ str.charCodeAt(i), 16777619);
    return h >>> 0;
}

function jitter(seed, amount) {
    const n = Math.sin(seed * 12.9898) * 43758.5453;
    return (n - Math.floor(n) - 0.5) * amount;
}

function drawStroke(ctx, stroke, x, y, size, seed) {
    ctx.beginPath();
    stroke.forEach(([px, py], index) => {
        const jx = jitter(seed + index * 17, size * 0.035);
        const jy = jitter(seed + index * 31, size * 0.035);
        const tx = x + px * size + jx;
        const ty = y + py * size + jy;
        if (index === 0) ctx.moveTo(tx, ty);
        else {
            const prev = stroke[index - 1];
            const mx = x + ((prev[0] + px) / 2) * size + jitter(seed + index * 47, size * 0.025);
            const my = y + ((prev[1] + py) / 2) * size + jitter(seed + index * 53, size * 0.025);
            ctx.quadraticCurveTo(mx, my, tx, ty);
        }
    });
    ctx.stroke();
}

export function drawThinGlyphText(ctx, text, x, y, options = {}) {
    const value = String(text || "").toUpperCase();
    const size = Number(options.size) || 58;
    const color = options.color || "#111";
    const lineWidth = Math.max(1, Number(options.lineWidth) || size * 0.07);
    const spacing = Number(options.spacing) || size * 0.77;
    const lineHeight = Number(options.lineHeight) || size * 1.12;
    const maxWidth = Number(options.maxWidth) || 620;
    const baseSeed = hash(value + color + Math.round(x) + ":" + Math.round(y));
    let cx = x;
    let cy = y;

    ctx.save();
    ctx.strokeStyle = color;
    ctx.lineWidth = lineWidth;
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    ctx.globalAlpha = options.opacity ?? 0.95;

    [...value].forEach((ch, i) => {
        if (ch === "\n") {
            cx = x;
            cy += lineHeight;
            return;
        }
        if (ch === " ") {
            cx += spacing * 0.65;
            return;
        }
        if (cx - x > maxWidth && ch !== " ") {
            cx = x;
            cy += lineHeight;
        }
        const glyph = GLYPHS[ch] || GLYPHS["?"];
        const seed = baseSeed + i * 101;
        glyph.forEach((stroke, strokeIndex) => drawStroke(ctx, stroke, cx, cy, size, seed + strokeIndex * 13));
        if (options.speckles !== false) {
            ctx.fillStyle = color;
            const specks = Math.max(1, Math.round(size / 18));
            for (let s = 0; s < specks; s += 1) {
                const sx = cx + (0.2 + Math.random() * 0.65) * size;
                const sy = cy + (0.08 + Math.random() * 0.88) * size;
                const r = Math.max(1, size * (0.008 + Math.random() * 0.012));
                ctx.globalAlpha = (options.opacity ?? 0.95) * (0.2 + Math.random() * 0.45);
                ctx.fillRect(Math.round(sx), Math.round(sy), Math.ceil(r), Math.ceil(r));
            }
            ctx.globalAlpha = options.opacity ?? 0.95;
        }
        cx += spacing;
    });
    ctx.restore();
}
